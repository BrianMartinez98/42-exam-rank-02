#include <unistd.h>

void	print_bits(unsigned char octet)
{
	char	bit;
	int		i;

	i = 8;
	while (i-- > 0)
	{
		bit = ((octet >> i) & 1) + '0';
		write(1, &bit, 1);
	}
}
